"""Pure-ASGI session-token middleware.

Every data route requires the X-LAF-Token header to match the per-session
token generated by whoever launched the backend (Tauri shell or dev
script). /health stays open for the startup probe; CORS preflight
(OPTIONS) is handled by the outer CORSMiddleware before reaching here.

Comparison uses hmac.compare_digest (constant-time).
"""

from __future__ import annotations

import hmac
import json
from typing import Any, Awaitable, Callable

Scope = dict[str, Any]
Receive = Callable[[], Awaitable[dict[str, Any]]]
Send = Callable[[dict[str, Any]], Awaitable[None]]
ASGIApp = Callable[[Scope, Receive, Send], Awaitable[None]]


async def _unauthorized(send: Send, detail: str) -> None:
    body = json.dumps({"detail": detail}).encode("utf-8")
    await send(
        {
            "type": "http.response.start",
            "status": 401,
            "headers": [
                (b"content-type", b"application/json"),
                (b"content-length", str(len(body)).encode("ascii")),
            ],
        }
    )
    await send({"type": "http.response.body", "body": body})


class TokenMiddleware:
    """Blocks non-health requests without the correct session token."""

    def __init__(self, app: ASGIApp, token: str) -> None:
        self.app = app
        self.token_bytes = token.encode("utf-8")

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http" or not self.token_bytes:
            await self.app(scope, receive, send)
            return
        if scope.get("method") == "OPTIONS" or scope.get("path") == "/health":
            await self.app(scope, receive, send)
            return

        headers = {k.lower(): v for k, v in scope.get("headers", [])}
        supplied = headers.get(b"x-laf-token", b"")
        if hmac.compare_digest(supplied, self.token_bytes):
            await self.app(scope, receive, send)
            return

        await _unauthorized(send, "invalid or missing X-LAF-Token")
